"""Matrix Market import and export for `adata import sparse` / `export sparse`.

The codec itself is `formats.mtx`; this module applies it to one entry of a
store.
"""

from __future__ import annotations

import sys
from contextlib import nullcontext
from pathlib import Path
from typing import Any

from rich.console import Console

from adata.core.csr_build import CsrAppender
from adata.core.recast import describe
from adata.elements.write import write_mapping
from adata.formats.common import _get_encoding_type, _resolve
from adata.formats.mtx import (
    EXPORT_BLOCK_ENTRIES,
    EntryMap,
    check_sparse,
    iter_matrix_entries,
    mtx_field,
    read_header,
    read_into,
    scan,
    value_dtype,
    write_entries,
    write_header,
)
from adata.formats.textio import create_binary
from adata.formats.validate import validate_dimensions
from adata.storage import is_dataset, is_group, is_zarr_group
from adata.util.path import norm_path


def export_mtx(
    root: Any,
    obj: str,
    out: Path | None,
    head: int | None,
    chunk_elements: int,
    in_memory: bool,
    console: Console,
) -> None:
    """Write a CSR/CSC matrix as Matrix Market, gzipped if `out` ends in .gz.

    Streams by blocks of at most `chunk_elements` rows (columns for CSC) and
    about a million entries, reading `indices` and `data` once per block.
    `in_memory` makes the whole matrix one block; the output is the same.
    """
    h5obj = _resolve(root, obj)
    if not is_group(h5obj):
        raise ValueError("MTX export requires a CSR/CSC matrix group (not a dataset).")

    enc = _get_encoding_type(h5obj)
    if enc not in ("csr_matrix", "csc_matrix"):
        raise ValueError(
            f"Target group encoding-type is {enc!r}; expected 'csr_matrix' or 'csc_matrix'."
        )
    if not all(is_dataset(h5obj.get(key)) for key in ("data", "indices", "indptr")):
        raise ValueError(
            "Sparse matrix group must contain datasets: data, indices, indptr"
        )
    matrix = describe(h5obj)
    check_sparse(matrix)
    n_rows, n_cols = matrix.shape
    nnz_data = matrix.nnz
    nnz = min(nnz_data, head) if head is not None and head > 0 else nnz_data

    comments = ["% generated by adata-cli"]
    if nnz < nnz_data:
        comments.append(f"% output limited to first {nnz}/{nnz_data} nonzero entries")

    to_stdout = out is None or str(out) == "-"
    if not to_stdout:
        out.parent.mkdir(parents=True, exist_ok=True)
    target = (
        nullcontext(sys.stdout.buffer)
        if to_stdout
        else create_binary(out, gzipped=out.suffix == ".gz")
    )
    status = (
        nullcontext()
        if to_stdout
        else console.status(f"[magenta]Exporting {obj} to {out}...[/]")
    )
    with target as fh, status:
        write_header(
            fh, field=mtx_field(matrix.dtype), n_rows=n_rows, n_cols=n_cols,
            nnz=nnz, comments=comments,
        )
        entries = iter_matrix_entries(
            matrix,
            transpose=False,
            block_entries=max(1, nnz_data) if in_memory else EXPORT_BLOCK_ENTRIES,
            max_majors=None if in_memory else max(1, int(chunk_elements)),
        )
        write_entries(fh, entries, limit=nnz)
    if not to_stdout:
        console.print(f"[green]Wrote[/] {out}")


def import_mtx(
    root: Any,
    obj: str,
    input_file: Path,
    console: Console,
) -> None:
    """Import a Matrix Market file as a CSR matrix, streaming it in two passes.

    Everything that can be wrong with the file is found by the first pass,
    before `obj` is touched. Integer values stay integers, `real` ones become
    float64, and duplicate entries are summed, as scipy does.
    """
    obj = norm_path(obj)
    header = read_header(input_file)
    shape = (header.n_rows, header.n_cols)
    validate_dimensions(root, obj, shape, console)

    emap = EntryMap(n_rows=header.n_rows, n_cols=header.n_cols)
    with console.status(f"[magenta]Checking {input_file.name}...[/]"):
        scanned = scan(header, emap)
    dtype = value_dtype(header, scanned)

    parts = obj.split("/")
    parent = root
    for part in parts[:-1]:
        parent = parent[part] if part in parent else write_mapping(parent, part)
    name = parts[-1]
    if name in parent:
        del parent[name]

    compression = None if is_zarr_group(root) else "gzip"
    appender = CsrAppender(
        parent, name, shape=shape, data_dtype=dtype, compression=compression
    )
    with console.status(f"[magenta]Importing {input_file.name}...[/]"):
        summed = read_into(header, emap, scanned, [[appender]], parent)
        nnz = appender.finish()

    if summed:
        console.print(
            f"[yellow]Warning:[/] {summed:,} duplicate entries were summed, as "
            "scipy does."
        )
    console.print(
        f"[green]Imported[/] {shape[0]}×{shape[1]} sparse matrix ({nnz} non-zero, "
        f"{dtype}) into '{obj}'"
    )
